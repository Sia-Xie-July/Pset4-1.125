"""Own evidence sufficiency, three-argument generation, and supported briefs."""
import sys
import os
import re
from copy import deepcopy
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lib.evidence import accepted_by_piece, eligible
from lib.model_provider import ask
from lib.records import canonical
from lib.schemas import BRIEF, CLAIM, REFERENCE, RESPONSES
from lib.stage_runtime import InvalidInput, OperationalFailure, records, run_directory, run_stage, snapshots


def response_schema(accepted, evidence=None):
    """Constrain generated identities to each piece's actual accepted versions."""
    schema = deepcopy(RESPONSES["create_briefs"])
    pieces = []
    coverage = {}
    if evidence is not None:
        for kind, preferred in (("feed", "01"), ("youtube", "02"), ("podcast", "03")):
            available = [piece for piece, keys in sorted(accepted.items())
                         if any(evidence.items[key]["kind"] == kind for key in keys)]
            if available:
                coverage[kind] = preferred if preferred in available else available[0]
    for piece, keys in sorted(accepted.items()):
        brief = deepcopy(BRIEF)
        brief["properties"]["piece_id"]["enum"] = [piece]
        # Reserve c91-c93 for coverage anchors so the model cannot collide with
        # a different ordinary claim while preserving all generated statements.
        claim_id = {"type": "string", "pattern": "^" + piece + r"-c(?:[1-9]|[1-8][0-9])$"}
        brief["properties"]["claims"]["items"]["properties"]["claim_id"] = claim_id
        refs = []
        for item_id, version in sorted(keys):
            ref = deepcopy(REFERENCE)
            ref["properties"]["item_id"] = {"type": "string", "enum": [item_id]}
            ref["properties"]["version_id"] = {"type": "string", "enum": [version]}
            if evidence is not None:
                key = item_id, version
                media = evidence.items[key]["kind"] != "feed"
                locator = deepcopy(REFERENCE["properties"]["locator"]["anyOf"][int(media)])
                if media:
                    ids = [re.escape(s["segment_id"]) for s in evidence.segments[key]]
                    locator["properties"]["segment_id"] = {"type": "string", "pattern": "^(?:" + "|".join(ids) + ")$"}
                # Any exact passage is allowed. Local reference validation checks
                # it against the full retained text, not a five-snippet menu.
                ref["properties"]["locator"] = locator
            refs.append(ref)
        brief["properties"]["claims"]["items"]["properties"]["evidence"]["items"] = {"anyOf": refs}
        for kind, assigned_piece in coverage.items():
            if assigned_piece != piece:
                continue
            source_refs = [ref for ref, key in zip(refs, sorted(keys)) if evidence.items[key]["kind"] == kind]
            anchor = deepcopy(CLAIM)
            anchor["properties"]["claim_id"] = {"type": "string", "enum": [piece + {"feed": "-c91", "youtube": "-c92", "podcast": "-c93"}[kind]]}
            anchor["properties"]["evidence"]["items"] = {"anyOf": source_refs}
            field = kind + "_claim"
            brief["properties"][field] = anchor
            brief["required"].append(field)
        pieces.append(brief)
    schema["properties"]["briefs"]["items"] = {"anyOf": pieces}
    return schema


def include_coverage_claims(briefs):
    # These claims are generated by the model under a source-kind constraint;
    # the normal exact-version, quote and publisher checks still assess them.
    for brief in briefs:
        existing = {claim["claim_id"]: claim for claim in brief["claims"]}
        for field in ("feed_claim", "youtube_claim", "podcast_claim"):
            claim = brief.pop(field, None)
            if claim is None:
                continue
            previous = existing.get(claim["claim_id"])
            if previous:
                if any(previous[key] != claim[key] for key in ("statement", "type")) or any(ref not in previous["evidence"] for ref in claim["evidence"]):
                    raise InvalidInput("Coverage claim conflicts with the same claim ID")
            else:
                brief["claims"].append(claim)
                existing[claim["claim_id"]] = claim


def main(metrics):
    run = run_directory()
    metadata, project, policy, prompt = snapshots(run, "create_briefs")
    decisions = records(sys.stdin)
    metrics["input_count"] = len(decisions)
    evidence = eligible(run, metadata)
    accepted = accepted_by_piece(evidence, decisions)
    for piece, keys in accepted.items():
        publishers = {evidence.items[key]["publisher_id"] for key in keys}
        if len(publishers) < 3:
            raise OperationalFailure(f"Insufficient accepted evidence for piece {piece}: need three independent publishers")
    selected = set().union(*accepted.values())
    if {evidence.items[key]["kind"] for key in selected} != {"feed", "youtube", "podcast"}:
        raise OperationalFailure("Accepted evidence does not cover all three required input types")
    if os.getenv('MODEL_PROVIDER', 'ollama_local') == 'ollama_local':
        from editorial.local_briefs import generate
        briefs = generate(run, metadata, project, policy, prompt, evidence, accepted, metrics)
        evidence.briefs(briefs, accepted)
        for brief in briefs:
            print(canonical(brief))
            metrics['output_count'] += 1
        return
    output = ask("create_briefs", run, metadata, policy, prompt,
        {"project": project, "as_of_date": metadata["as_of_date"], "decisions": decisions,
         "accepted_evidence": evidence.payload(selected),
         "accepted_refs_by_piece": {piece: [{"item_id": key[0], "version_id": key[1]}
                                             for key in sorted(keys)] for piece, keys in accepted.items()},
         "locator_instructions": "For written evidence copy any literal passage from the retained full source text exactly. Media segment IDs must come from that exact item's supplied segments. Do not invent quotations or segments.",
         "coverage_instructions": "Each piece must actually cite at least three distinct publisher_id groups; choose any relevant accepted publishers, not a predetermined trio. The schema also requires media-kind anchors on assigned pieces. Their IDs are reserved; use different IDs for ordinary claims. Integrate the anchors into the argument; the component includes them in the final claims array. Never invent evidence to fill a requirement. Claim strength, synthesis quality and entailment are for human editorial review, not an additional model judging pass.",
         "piece_requirements": {
             "01": "What changed and why it matters. Actually cite at least one feed passage in a claim.",
             "02": "Scrutinize claims and tensions. Actually cite at least one YouTube segment in a claim.",
             "03": "Implications and what to watch. REQUIRED: actually cite at least one accepted PODCAST segment in a claim. A podcast being accepted or mentioned elsewhere does not count. Use the podcast's original observations and state their limitations."}},
        response_schema(accepted, evidence), metrics)
    briefs = output["briefs"]
    include_coverage_claims(briefs)
    evidence.briefs(briefs, accepted)
    for brief in sorted(briefs, key=lambda b: b["piece_id"]):
        print(canonical(brief))
        metrics["output_count"] += 1


if __name__ == "__main__":
    sys.exit(run_stage(main))
